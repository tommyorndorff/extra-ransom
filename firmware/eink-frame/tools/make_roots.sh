#!/bin/sh
# Regenerates include/roots.h: the root CAs the frame trusts for https://www.extra-ransom.net.
# Cloudflare's Universal SSL issues from Google Trust Services, Let's Encrypt or SSL.com, so all
# of their current roots are included. macOS only (reads the system root keychain).
set -eu
cd "$(dirname "$0")/.."
KC=/System/Library/Keychains/SystemRootCertificates.keychain
OUT=include/roots.h
{
  echo "// Generated by tools/make_roots.sh on $(date +%F). Do not edit by hand."
  echo "#pragma once"
  echo "static const char ROOT_CAS[] ="
  for n in "GTS Root R1" "GTS Root R4" "GlobalSign Root CA" "ISRG Root X1" "ISRG Root X2" \
           "SSL.com Root Certification Authority RSA" "SSL.com Root Certification Authority ECC"; do
    pem=$(security find-certificate -c "$n" -p "$KC")
    exp=$(echo "$pem" | openssl x509 -noout -enddate | cut -d= -f2)
    echo "  // $n (expires $exp)"
    echo "$pem" | sed 's/^/  "/; s/$/\\n"/'
  done
  echo "  ;"
} > "$OUT"
echo "wrote $OUT"
